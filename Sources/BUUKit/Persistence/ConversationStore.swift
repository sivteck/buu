import Foundation

/// Persists conversations and the images attached to them.
public actor ConversationStore {
    private let fileStore: FileStore

    public init(fileStore: FileStore = FileStore()) {
        self.fileStore = fileStore
    }

    // MARK: - Conversations

    public func loadAll() async -> [Conversation] {
        try? await fileStore.prepare()
        let directory = await fileStore.conversationsDirectory
        let files = await fileStore.contentsOfDirectory(at: directory)
        var conversations: [Conversation] = []
        for file in files where file.pathExtension == "json" {
            if let conversation = try? await fileStore.readJSON(Conversation.self, from: file) {
                conversations.append(conversation)
            }
        }
        conversations.sort { $0.updatedAt > $1.updatedAt }
        return conversations
    }

    public func save(_ conversation: Conversation) async {
        try? await fileStore.prepare()
        let url = await fileStore.conversationsDirectory
            .appendingPathComponent(conversation.id.uuidString)
            .appendingPathExtension("json")
        try? await fileStore.writeJSON(conversation, to: url)
    }

    public func delete(_ conversation: Conversation) async {
        let url = await fileStore.conversationsDirectory
            .appendingPathComponent(conversation.id.uuidString)
            .appendingPathExtension("json")
        try? await fileStore.removeItem(at: url)
        for turn in conversation.turns {
            for image in turn.images {
                try? await deleteAttachment(image)
            }
        }
    }

    // MARK: - Attachments

    public func storeAttachment(data: Data, mimeType: String) async throws -> ImageAttachment {
        try? await fileStore.prepare()
        let id = UUID()
        let ext = Self.fileExtension(for: mimeType)
        let fileName = id.uuidString + ext
        let url = await fileStore.attachmentsDirectory.appendingPathComponent(fileName)
        try await fileStore.write(data, to: url)
        let size = ImageProcessor.pixelSize(of: data)
        return ImageAttachment(
            id: id,
            fileName: fileName,
            mimeType: mimeType,
            pixelWidth: size?.width ?? 0,
            pixelHeight: size?.height ?? 0,
            byteCount: data.count
        )
    }

    public func loadAttachmentData(_ attachment: ImageAttachment) async -> Data? {
        let url = await fileStore.attachmentsDirectory.appendingPathComponent(safeName(for: attachment))
        return try? await fileStore.readData(from: url)
    }

    public func deleteAttachment(_ attachment: ImageAttachment) async throws {
        let url = await fileStore.attachmentsDirectory.appendingPathComponent(safeName(for: attachment))
        try await fileStore.removeItem(at: url)
    }

    /// Attachment names are generated by the app, but the conversation files on
    /// disk could have been tampered with – never build a path from anything
    /// but the last path component.
    private func safeName(for attachment: ImageAttachment) -> String {
        let name = URL(fileURLWithPath: attachment.fileName).lastPathComponent
        return name.isEmpty ? UUID().uuidString : name
    }

    static func fileExtension(for mimeType: String) -> String {
        switch mimeType.lowercased() {
        case "image/png": return ".png"
        case "image/jpeg", "image/jpg": return ".jpg"
        case "image/gif": return ".gif"
        case "image/heic", "image/heif": return ".heic"
        case "image/webp": return ".webp"
        case "image/tiff": return ".tiff"
        default: return ".bin"
        }
    }
}
